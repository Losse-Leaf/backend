func initCityEntries() {
	initCityOnce.Do(func() {
		list := make([]cityEntry, 0, len(CityNameToCode))
		for name, code := range CityNameToCode {
			if len([]rune(name)) >= 2 {
				list = append(list, cityEntry{Name: name, Code: code})
			}
		}
		sort.Slice(list, func(i, j int) bool {
			lenI := len([]rune(list[i].Name))
			lenJ := len([]rune(list[j].Name))
			if lenI != lenJ {
				return lenI > lenJ
			}
			return list[i].Name < list[j].Name
		})
		sortedCityList = list
	})
}

// ResolveCityCodeAndName 规范化清洗并防御性反解城市代码与城市名 (方案 A)
func ResolveCityCodeAndName(cityCode, cityName, location string) (cleanCode, cleanName, cleanLoc string) {
	initCityEntries()
	cityCode = strings.TrimSpace(cityCode)
	cityName = strings.TrimSpace(cityName)
	location = strings.TrimSpace(location)

	// 1. 若传入的 cityCode 满足 6 位纯数字，尝试匹配已知全称
	if cityCodeRegex.MatchString(cityCode) {
		if standardName, ok := CodeToCityName[cityCode]; ok {
			cleanCode = cityCode
			if cityName == "" {
				cleanName = standardName
			} else {
				cleanName = cityName
			}
			cleanLoc = location
			return
		}
		// 即使不在内置字典但满足 6 位国标格式，也保留
		cleanCode = cityCode
		cleanName = cityName
		cleanLoc = location
		return
	}

	// 2. 若 cityCode 为空或非合法 6 位，尝试从 cityName 与 location 模糊反查
	textsToSearch := []string{cityName, location}
	for _, text := range textsToSearch {
		if text == "" {
			continue
		}
		for _, entry := range sortedCityList {
			if strings.Contains(text, entry.Name) {
				cleanCode = entry.Code
				if standardName, ok := CodeToCityName[entry.Code]; ok {
					cleanName = standardName
				} else {
					cleanName = entry.Name
				}
				cleanLoc = location
				return
			}
		}
	}

	// 3. 实在无法反解，且原 code 不合法，则清空 code，保留文本
	cleanCode = ""
	cleanName = cityName
	cleanLoc = location
	return
}
